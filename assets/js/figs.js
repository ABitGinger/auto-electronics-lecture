  /* 折线图 */
  function chart(o) {
    var w = o.w || 640, h = o.h || 300, pl = 52, pr = 18, pt = 20, pb = 38;
    var xs = o.xr, ys = o.yr;
    function X(v) { return pl + (w - pl - pr) * (v - xs[0]) / (xs[1] - xs[0]); }
    function Y(v) { return h - pb - (h - pt - pb) * (v - ys[0]) / (ys[1] - ys[0]); }
    var s = '<svg viewBox="0 0 ' + w + ' ' + h + '" xmlns="http://www.w3.org/2000/svg" font-family="sans-serif">';
    for (var i = 0; i <= 4; i++) {
      var yv = ys[0] + (ys[1] - ys[0]) * i / 4;
      s += '<line x1="' + pl + '" y1="' + Y(yv) + '" x2="' + (w - pr) + '" y2="' + Y(yv) + '" stroke="' + LINE + '"/>' +
        '<text x="' + (pl - 8) + '" y="' + (Y(yv) + 3.5) + '" text-anchor="end" font-size="9.5" fill="' + DIM + '" font-family="monospace">' + (o.yfmt ? o.yfmt(yv) : Math.round(yv * 100) / 100) + '</text>';
    }
    for (var k = 0; k <= 5; k++) {
      var xv = xs[0] + (xs[1] - xs[0]) * k / 5;
      s += '<line x1="' + X(xv) + '" y1="' + pt + '" x2="' + X(xv) + '" y2="' + (h - pb) + '" stroke="' + LINE + '" opacity=".45"/>' +
        '<text x="' + X(xv) + '" y="' + (h - pb + 16) + '" text-anchor="middle" font-size="9.5" fill="' + DIM + '" font-family="monospace">' + (o.xfmt ? o.xfmt(xv) : Math.round(xv)) + '</text>';
    }
    s += '<text x="' + (w / 2) + '" y="' + (h - 4) + '" text-anchor="middle" font-size="10.5" fill="' + DIM + '">' + esc(o.xl || '') + '</text>';
    s += '<text x="14" y="' + (pt + 8) + '" font-size="10" fill="' + DIM + '">' + esc(o.yl || '') + '</text>';
    (o.bands || []).forEach(function (b) {
      s += '<rect x="' + X(b[0]) + '" y="' + pt + '" width="' + (X(b[1]) - X(b[0])) + '" height="' + (h - pt - pb) + '" fill="' + (b.c || C.gr) + '" opacity=".08"/>';
      if (b.t) s += '<text x="' + ((X(b[0]) + X(b[1])) / 2) + '" y="' + (h - pb - 8) + '" text-anchor="middle" font-size="10.5" fill="' + (b.c || C.gr) + '">' + esc(b.t) + '</text>';
    });
    (o.series || []).forEach(function (se) {
      var pts = se.p.map(function (p) { return X(p[0]) + ',' + Y(p[1]); }).join(' ');
      s += '<polyline points="' + pts + '" fill="none" stroke="' + (se.c || C.cy) + '" stroke-width="2.2" stroke-linejoin="round"' + (se.dash ? ' stroke-dasharray="5 4"' : '') + '/>';
    });
    (o.dots || []).forEach(function (d) {
      var px = (d.x != null ? d.x : d[0]), py = (d.y != null ? d.y : d[1]);
      if (px == null || py == null) return;
      s += '<circle cx="' + X(px) + '" cy="' + Y(py) + '" r="4" fill="' + (d.c || C.or) + '" stroke="#0f1622" stroke-width="1.5"/>' +
        (d.t ? (X(px) > 480
          ? '<text x="' + (X(px) - 9) + '" y="' + (Y(py) - 7) + '" text-anchor="end" font-size="10.5" fill="' + (d.c || C.or) + '">' + esc(d.t) + '</text>'
          : '<text x="' + (X(px) + 9) + '" y="' + (Y(py) - 7) + '" font-size="10.5" fill="' + (d.c || C.or) + '">' + esc(d.t) + '</text>') : '');
    });
    return s + '</svg>';
  }

  /* PWM 方波 */
  function pwm(duty) {
    var w = 640, h = 220, pl = 40, pr = 20, top = 50, bot = 150, T = 100, n = 5;
    var s = '<svg viewBox="0 0 ' + w + ' ' + h + '" xmlns="http://www.w3.org/2000/svg" font-family="sans-serif">';
    s += '<line x1="' + pl + '" y1="' + bot + '" x2="' + (w - pr) + '" y2="' + bot + '" stroke="' + LINE + '"/>';
    s += '<line x1="' + pl + '" y1="' + top + '" x2="' + (w - pr) + '" y2="' + top + '" stroke="' + LINE + '" opacity=".5" stroke-dasharray="4 4"/>';
    var x = pl, d = duty, pts = [];
    for (var i = 0; i < n; i++) {
      var tw = (w - pl - pr) / n;
      pts.push([x, bot], [x, top], [x + tw * d, top], [x + tw * d, bot], [x + tw, bot]);
      if (i === 0) {
        s += '<line x1="' + (x + tw * d) + '" y1="' + top + '" x2="' + (x + tw * d) + '" y2="' + (bot + 26) + '" stroke="' + C.or + '" stroke-dasharray="3 3"/>';
        s += '<line x1="' + x + '" y1="' + (bot + 26) + '" x2="' + (x + tw * d) + '" y2="' + (bot + 26) + '" stroke="' + C.or + '"/>';
        s += '<line x1="' + x + '" y1="' + (bot + 20) + '" x2="' + x + '" y2="' + (bot + 32) + '" stroke="' + C.or + '"/>';
        s += '<line x1="' + (x + tw) + '" y1="' + (bot + 20) + '" x2="' + (x + tw) + '" y2="' + (bot + 32) + '" stroke="' + C.or + '"/>';
        s += '<text x="' + (x + tw * d / 2) + '" y="' + (bot + 42) + '" text-anchor="middle" font-size="10.5" fill="' + C.or + '">t_on</text>';
        s += '<text x="' + (x + tw / 2) + '" y="' + (bot + 58) + '" text-anchor="middle" font-size="10.5" fill="' + DIM + '">周期 T</text>';
      }
      x += tw;
    }
    s += '<polyline points="' + pts.map(function (p) { return p[0] + ',' + p[1]; }).join(' ') + '" fill="none" stroke="' + C.cy + '" stroke-width="2.2"/>';
    s += '<text x="' + (w / 2) + '" y="26" text-anchor="middle" font-size="11.5" fill="' + INK + '">占空比 D = t_on / T × 100% = ' + Math.round(d * 100) + '%　→　平均电压 U_avg = ' + (d * 12).toFixed(1) + ' V（母线 12 V）</text>';
    s += '<text x="' + pl + '" y="' + (top - 6) + '" font-size="10" fill="' + DIM + '">Us</text>';
    s += '<text x="' + pl + '" y="' + (bot + 6) + '" font-size="10" fill="' + DIM + '">0</text>';
    return s + '</svg>';
  }

